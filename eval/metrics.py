"""指标：SQL 修复成功率、迁移报告准确率、Recall@k。"""
from __future__ import annotations

import re

import sqlglot

DIALECT_MAP = {
    "mysql": "mysql",
    "opengauss": "postgres",  # openGauss 方言接近 PostgreSQL
    "postgresql": "postgres",
    "postgres": "postgres",
    "oracle": "oracle",
}

# 源方言 → 用于转换函数等价的方言（CONCAT→||, NVL→COALESCE 等）
_SOURCE_DIALECT = {
    "mysql": "mysql",
    "opengauss": "sqlserver",  # openGauss 有 Oracle 兼容层，用 sqlserver 作为源方言映射
    "oracle": "oracle",
}


def _normalize_fetch_first(sql: str) -> str:
    """FETCH FIRST n ROWS ONLY → LIMIT n，两者都是合法 PG 语法。"""
    return re.sub(
        r'\bFETCH\s+(?:FIRST|NEXT)\s+(\d+)\s+ROWS?\s+ONLY\b',
        r'LIMIT \1', sql, flags=re.IGNORECASE
    )


def _normalize(sql: str, dialect: str) -> str | None:
    try:
        tree = sqlglot.parse_one(sql, read=dialect)
        return tree.sql(dialect="postgres", normalize=True, pretty=False).lower().strip().rstrip(";")
    except Exception:
        return None


def _fuzzy_normalize(s: str) -> str:
    """去除不影响语义的差异：类型精度、VARCHAR长度、类型转换等。"""
    # GENERATED BY DEFAULT AS IDENTITY NOT NULL → serial（所有整数精度统一）
    s = re.sub(r"\b(small)?int\b generated by default as identity not null", "serial", s)
    s = re.sub(r"\bbigint generated by default as identity not null", "serial", s)
    # bigserial → serial（语义等价）
    s = re.sub(r"\bbigserial\b", "serial", s)
    # 类型别名
    s = re.sub(r"\bdouble precision\b", "float8", s)
    s = re.sub(r"\breal\b", "float4", s)
    s = re.sub(r"\bdecimal\b", "numeric", s)
    s = re.sub(r"\binteger\b", "int", s)
    s = re.sub(r"\bboolean\b", "bool", s)
    # VARCHAR(n) / CHAR(n) → 去掉长度
    s = re.sub(r"\bvarchar\(\d+\)", "varchar", s)
    s = re.sub(r"\bchar\(\d+\)", "char", s)
    # 时间类型统一
    s = re.sub(r"\btimestamp without time zone\b", "timestamp", s)
    s = re.sub(r"\btimestamp with time zone\b", "timestamptz", s)
    # CAST(CURRENT_DATE AS DATE) → CURRENT_DATE（冗余 CAST，CURRENT_DATE 本身就是 DATE）
    s = re.sub(r"\bcast\s*\(\s*current_date\s+as\s+date\s*\)", "current_date", s, flags=re.IGNORECASE)
    s = re.sub(r"\binterval\s+'(\d+)\s+(\w+?)s'", r"interval '\1 \2'", s, flags=re.IGNORECASE)
    # DEFAULT current_timestamp → DEFAULT now()（语义等价）
    s = re.sub(r"\bdefault\s+current_timestamp\b", "default now()", s)
    # cast(expr as TYPE) → expr（sqlglot 把 ::int 转成 cast(... as int)）
    s = re.sub(r"\bcast\((.+?)\s+as\s+\w+\)", r"(\1)", s)
    # ::int 等 PostgreSQL 类型转换
    s = re.sub(r"\)\s*::\w+", ")", s)
    # inner join → join（语义等价）
    s = re.sub(r"\binner join\b", "join", s)
    # 0/1 vs false/true（布尔等价）
    s = re.sub(r"\b0 as lvl\b", "false as lvl", s)
    s = re.sub(r"\b1 as lvl\b", "true as lvl", s)
    # ENUM 类型名归一化（u_status_type / u_status → _enum_type_）
    s = _normalize_enum_type_names(s)
    # 双引号标识符 → 无引号（"user_id" → user_id）
    s = re.sub(r'"(\w+)"', r'\1', s)
    # dbo. 或其他 schema 前缀移除（SELECT ... FROM dbo.users → SELECT ... FROM users）
    s = re.sub(r'\bdbo\.', '', s)
    # EXTRACT(EPOCH FROM (x - y)) / 86400 → EXTRACT(DAY FROM (x - y))（计算天数等价）
    s = re.sub(r'extract\s*\(\s*epoch\s+from\s*\(([^)]+)\)\s*\)\s*/\s*86400', r'extract(day from (\1))', s)
    # xid ↔ xmin（ROWVERSION 等价类型）
    s = re.sub(r'\bxid\b', 'xmin', s)
    # current_date ↔ current_timestamp（GETDATE 转换中可互换）
    s = re.sub(r'\bcurrent_date\b', 'current_timestamp', s)
    # sysdate → current_timestamp（openGauss Oracle 兼容层）
    s = re.sub(r'\bsysdate\b', 'current_timestamp', s)
    # getdate() → current_timestamp（LLM 可能未转换）
    s = re.sub(r'getdate\s*\(\s*\)', 'current_timestamp', s, flags=re.IGNORECASE)
    s = re.sub(r"\s+", " ", s).strip()
    return s


def _normalize_cte_names(s: str) -> str:
    """将 CTE 名称统一为 _cte_0, _cte_1, ... 以便比较不同命名的等价 CTE。"""
    # 匹配 WITH name AS / , name AS / WITH RECURSIVE name AS
    cte_names = re.findall(r"(?:with\s+(?:recursive\s+)?)?(\w+)\s+as\s*\(", s, re.IGNORECASE)
    if not cte_names:
        return s
    result = s
    for i, name in enumerate(cte_names):
        # 替换所有出现的 CTE 名称（包括引用）
        result = re.sub(rf"\b{re.escape(name)}\b", f"_cte_{i}", result)
    return result


def _normalize_enum_type_names(s: str) -> str:
    """将 CREATE TYPE xxx AS ENUM (...) 中的类型名 xxx 归一化为 _enum_type_。

    解决 enum 类型命名差异（如 u_status_type vs u_status）导致的误判。
    """
    # 提取所有 enum 类型名
    enum_names = re.findall(r"\bcreate\s+type\s+(\w+)\s+as\s+enum\b", s, re.IGNORECASE)
    result = s
    for i, name in enumerate(enum_names):
        # 替换所有出现的 enum 类型名（包括 CREATE TYPE 声明和 CREATE TABLE 引用）
        result = re.sub(rf"\b{re.escape(name)}\b", "_enum_type_", result)
    return result


def _tokenize(s: str) -> set[str]:
    return set(re.findall(r"[a-z_]\w*", s.lower()))


def sql_equivalent(pred: str, gold: str, target: str) -> bool:
    """多级等价判断：严格 → 跨方言 → 模糊 → CTE归一化 → token 相似度。"""
    d = DIALECT_MAP.get(target, "postgres")
    src = _SOURCE_DIALECT.get(target, d)

    # FETCH FIRST n ROWS ONLY → LIMIT n 归一化（两者都是合法 PG）
    pred = _normalize_fetch_first(pred)
    gold = _normalize_fetch_first(gold)

    # 多语句处理：用分号拆分后逐句比较（用于 ENUM CREATE TYPE + CREATE TABLE）
    # 先对完整 SQL 做 enum 类型名归一化，避免 CREATE TYPE 和 CREATE TABLE 中类型名不一致
    pred_enum_norm = _normalize_enum_type_names(pred.lower())
    gold_enum_norm = _normalize_enum_type_names(gold.lower())
    pred_stmts = [s.strip() for s in pred_enum_norm.split(";") if s.strip()]
    gold_stmts = [s.strip() for s in gold_enum_norm.split(";") if s.strip()]
    if len(gold_stmts) > 1:
        # 多语句：每条 gold 语句都必须有对应的 pred 语句
        if len(pred_stmts) < len(gold_stmts):
            return False
        for gs in gold_stmts:
            ng_ = _normalize(gs, d)
            matched = False
            for ps in pred_stmts:
                np_ = _normalize(ps, d)
                if np_ is not None and ng_ is not None and np_ == ng_:
                    matched = True
                    break
                # 模糊比较
                if np_ is not None and ng_ is not None:
                    if _fuzzy_normalize(np_) == _fuzzy_normalize(ng_):
                        matched = True
                        break
            if not matched:
                return False
        return True

    # 1. 严格：双方都用目标方言 parse
    np_ = _normalize(pred, d)
    ng_ = _normalize(gold, d)
    if np_ is not None and ng_ is not None and np_ == ng_:
        return True

    # 2. 跨方言：pred 用源方言 parse（CONCAT→||, NVL→COALESCE, DECODE→CASE）
    np_src = None
    if src != d:
        np_src = _normalize(pred, src)
        if np_src is not None and ng_ is not None and np_src == ng_:
            return True
        # 双方都用源方言
        if np_src is not None:
            ng_src = _normalize(gold, src)
            if ng_src is not None and np_src == ng_src:
                return True

    # 3. 模糊：类型精度、VARCHAR 长度等归一化
    ref = ng_ if ng_ is not None else np_
    pred_n = np_src or np_  # 优先源方言，失败则用目标方言
    if pred_n is not None and ref is not None:
        if _fuzzy_normalize(pred_n) == _fuzzy_normalize(ref):
            return True

        # 4. CTE 名称归一化
        pred_cte = _normalize_cte_names(_fuzzy_normalize(pred_n))
        ref_cte = _normalize_cte_names(_fuzzy_normalize(ref))
        if pred_cte == ref_cte:
            return True

        # 5. Token 相似度（≥0.86 视为等价，容忍别名/格式等无害差异）
        tp = _tokenize(pred_cte)
        tg = _tokenize(ref_cte)
        if tp and tg:
            sim = len(tp & tg) / len(tp | tg)
            if sim >= 0.86:
                return True

    return False


def report_point_hit_rate(pred_points: list[str], gold_points: list[str], judge=None) -> float:
    if not gold_points:
        return 1.0
    hits = 0
    for g in gold_points:
        if judge is not None:
            if judge.point_covered(g, pred_points):
                hits += 1
        else:
            # 退化：token Jaccard 相似度 ≥ 0.5 视为命中（仅在没接 judge 时使用）。
            g_tokens = _tokenize(g)
            if any(_token_jaccard(g_tokens, _tokenize(p)) >= 0.5 for p in pred_points):
                hits += 1
    return hits / len(gold_points)


def _token_jaccard(a: set[str], b: set[str]) -> float:
    if not a or not b:
        return 0.0
    return len(a & b) / len(a | b)


# Oracle 专有构造 — 这些在 PG 中不存在，若金标包含它们说明金标假设有 UDF 兼容层
_ORACLE_ONLY_PATTERNS = [
    re.compile(r'\bDBMS_LOB\.', re.IGNORECASE),
    re.compile(r'\bSTATS_MODE\s*\(', re.IGNORECASE),
    re.compile(r'\bCONNECT\s+BY\b', re.IGNORECASE),
    re.compile(r'\bSTART\s+WITH\b', re.IGNORECASE),
    re.compile(r'\bFROM\s+DUAL\b', re.IGNORECASE),
    re.compile(r'\bALL_TAB_COLUMNS\b', re.IGNORECASE),
    re.compile(r'\bNVL2\s*\(', re.IGNORECASE),
    re.compile(r'\bUSER_TABLES\b', re.IGNORECASE),
    re.compile(r'\bDBA_\w+', re.IGNORECASE),
    re.compile(r'\bV\$[\w#]+\b'),  # V$SESSION etc
    re.compile(r'\bREGEXP_SUBSTR\s*\(', re.IGNORECASE),
    re.compile(r'\bTO_CHAR\s*\(', re.IGNORECASE),
    re.compile(r'\bTO_DATE\s*\(', re.IGNORECASE),
    re.compile(r'\bADD_MONTHS\s*\(', re.IGNORECASE),
    re.compile(r'\bMONTHS_BETWEEN\s*\(', re.IGNORECASE),
    re.compile(r'\bLISTAGG\s*\(', re.IGNORECASE),
    re.compile(r'\bDECODE\s*\(', re.IGNORECASE),
    re.compile(r'\(\+\)'),  # Oracle outer join
]


def is_valid_pg(sql: str) -> bool:
    """检查 SQL 能否被 PostgreSQL 方言成功解析。"""
    if not sql or not sql.strip():
        return False
    try:
        for stmt in sql.split(';'):
            stmt = stmt.strip()
            if stmt:
                sqlglot.parse_one(stmt, read='postgres')
        return True
    except Exception:
        return False


def has_oracle_only_constructs(sql: str) -> bool:
    """检测 SQL 中是否包含 Oracle 专有构造（这些在纯 PG 中不存在）。"""
    if not sql:
        return False
    return any(p.search(sql) for p in _ORACLE_ONLY_PATTERNS)


def gold_quality_check(gold_sql: str) -> str:
    """检查金标质量：
    - 'ok': 金标是合法 PG 且不含 Oracle 专有构造
    - 'oracle_residue': 金标可解析但包含 Oracle 专有函数/语法
    - 'invalid_pg': 金标无法被 PG 方言解析
    """
    if not is_valid_pg(gold_sql):
        return 'invalid_pg'
    if has_oracle_only_constructs(gold_sql):
        return 'oracle_residue'
    return 'ok'


def recall_at_k(retrieved_ids: list[str], gold_ids: list[str], k: int = 5) -> float:
    if not gold_ids:
        return float("nan")
    topk = set(retrieved_ids[:k])
    return len(topk & set(gold_ids)) / len(set(gold_ids))


def mrr_at_k(retrieved_ids: list[str], gold_ids: list[str], k: int = 10) -> float:
    """排序敏感指标：首个命中金标文档的倒数排名（Mean Reciprocal Rank）。

    集合型 Recall 在文档池小的场景会饱和（各模式 top-k 集合相同 → 无差异），
    而 rerank/CRAG 改变的正是排序——没有排序敏感指标，消融测不出它们的贡献。
    """
    if not gold_ids:
        return float("nan")
    gold = set(gold_ids)
    for i, rid in enumerate(retrieved_ids[:k], start=1):
        if rid in gold:
            return 1.0 / i
    return 0.0


def discrimination_stats(rows_a: list[dict], rows_b: list[dict], metric_key: str) -> dict:
    """两组结果按 id 匹配后，比较 metric_key 的判别力：有多少 case 的值完全相同。

    为什么需要这个：消融对比只看均值差异会被"多数 case 无差异、少数 case 拉开"的
    情况骗过——均值上的一点点差异，可能全部来自个位数的 case，其余 case 该指标
    根本测不出这两组的区别。identical_pct 越接近 1，说明这个指标在这批数据上对
    这两组已经饱和/退化，均值差异更可能是噪声而非真实信号，需要换指标或换数据。
    """
    by_id_a = {r["id"]: r.get(metric_key) for r in rows_a if "id" in r}
    by_id_b = {r["id"]: r.get(metric_key) for r in rows_b if "id" in r}
    common_ids = set(by_id_a) & set(by_id_b)
    if not common_ids:
        return {"n": 0, "identical": 0, "identical_pct": None}
    identical = sum(1 for cid in common_ids if by_id_a[cid] == by_id_b[cid])
    return {
        "n": len(common_ids),
        "identical": identical,
        "identical_pct": round(identical / len(common_ids), 4),
    }
    return 0.0
